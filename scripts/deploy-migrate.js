#!/usr/bin/env node

// ---------------------------------------------------------------------------
// اعمال خودکار تغییرهای دیتابیس هنگام نصب روی سرور
// ---------------------------------------------------------------------------
// روی هاست cPanel، تنها کاری که کاربر انجام می‌دهد زدن دکمه‌ی «Run NPM Install»
// و بعد «Restart» است. تا پیش از این، migration های جدید دیتابیس با آن دکمه
// اجرا نمی‌شدند؛ نتیجه این بود که کدِ تازه روی سرور می‌رفت ولی ستون‌های جدید
// (مثل tags و step) در دیتابیس نبودند و قابلیت‌های تازه کار نمی‌کردند.
//
// «migrate deploy» فقط migration های اجرانشده را اضافه می‌کند و هیچ‌وقت دیتابیس
// را ریست نمی‌کند، بنابراین اجرای دوباره‌اش بی‌خطر است.
//
// اگر این مرحله شکست بخورد عمداً کل نصب را خراب نمی‌کنیم — چون آن‌وقت برنامه
// اصلاً بالا نمی‌آید. به‌جایش یک هشدار واضح چاپ می‌شود.

const { spawnSync } = require('child_process');

if (!process.env.DATABASE_URL && !require('fs').existsSync('.env')) {
  console.log('[migrate] DATABASE_URL تعریف نشده است — این مرحله رد شد.');
  process.exit(0);
}

const result = spawnSync(
  'npx',
  // prisma.config.js مسیر schema و migrationهای MariaDB را می‌دهد
  ['prisma', 'migrate', 'deploy'],
  { stdio: 'inherit', shell: true }
);

if (result.status === 0) {
  console.log('[migrate] تغییرهای دیتابیس با موفقیت اعمال شد.');
  process.exit(0);
}

console.warn('');
console.warn('=============================================================');
console.warn('هشدار: اعمال تغییرهای دیتابیس انجام نشد.');
console.warn('برنامه بالا می‌آید، اما قابلیت‌های جدید ممکن است کار نکنند.');
console.warn('معمولاً یعنی DATABASE_URL در فایل .env روی سرور درست نیست.');
console.warn('=============================================================');
console.warn('');
process.exit(0);
